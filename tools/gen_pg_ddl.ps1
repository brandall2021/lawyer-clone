$ErrorActionPreference = 'Stop'
$s = 'C:\Users\brandall\Documents\Default Project\lawyer-clone\db-export\schema'
$outDir = 'C:\Users\brandall\Documents\Default Project\lawyer-clone\db-export\pg'
New-Item -ItemType Directory -Path $outDir -Force | Out-Null

$cols = (Get-Content "$s\01_columns_keys.json" -Raw | ConvertFrom-Json)[0]
$idx  = (Get-Content "$s\01_columns_keys.json" -Raw | ConvertFrom-Json)[1]
$idxc = (Get-Content "$s\01_columns_keys.json" -Raw | ConvertFrom-Json)[2]

function Map-SqlType($dtype, $maxlen, $prec, $scale) {
    switch ($dtype.ToLower()) {
        'smallint'        { 'smallint' }
        'tinyint'         { 'smallint' }
        'int'             { 'integer' }
        'bigint'          { 'bigint' }
        'bit'             { 'boolean' }
        'decimal'         { "numeric($prec,$scale)" }
        'numeric'         { "numeric($prec,$scale)" }
        'money'           { 'numeric(19,4)' }
        'smallmoney'      { 'numeric(10,4)' }
        'float'           { 'double precision' }
        'real'            { 'real' }
        'datetime'        { 'timestamp' }
        'datetime2'       { 'timestamp' }
        'smalldatetime'   { 'timestamp' }
        'date'            { 'date' }
        'time'            { 'time' }
        'datetimeoffset'  { 'timestamptz' }
        'char'            { "varchar($maxlen)" }
        'varchar'         { if ($maxlen -eq -1) { 'text' } else { "varchar($maxlen)" } }
        'nchar'           { "varchar($([int]($maxlen/2)))" }
        'nvarchar'        { if ($maxlen -eq -1) { 'text' } else { "varchar($([int]($maxlen/2)))" } }
        'text'            { 'text' }
        'ntext'           { 'text' }
        'binary'          { 'bytea' }
        'varbinary'       { 'bytea' }
        'image'           { 'bytea' }
        'timestamp'       { 'bytea' }
        'uniqueidentifier'{ 'uuid' }
        'xml'             { 'xml' }
        default           { 'text' }
    }
}

$idxMap = @{}
foreach ($r in (Get-Content "$s\01_columns_keys.json" -Raw | ConvertFrom-Json)[1]) {
    if (-not $idxMap.ContainsKey($r.tbl)) { $idxMap[$r.tbl] = New-Object System.Collections.ArrayList }
    [void]$idxMap[$r.tbl].Add($r)
}
$idxCols = @{}
foreach ($r in (Get-Content "$s\01_columns_keys.json" -Raw | ConvertFrom-Json)[2]) {
    $k = "$($r.tbl)|$($r.idx_name)"
    if (-not $idxCols.ContainsKey($k)) { $idxCols[$k] = New-Object System.Collections.ArrayList }
    [void]$idxCols[$k].Add($r)
}

$tables = ($cols.tbl | Sort-Object -Unique)
$lines = New-Object System.Collections.ArrayList
[void]$lines.Add('-- Generated PostgreSQL DDL for LawyerTools50')
[void]$lines.Add('BEGIN;')

foreach ($t in $tables) {
    $tcols = $cols | Where-Object { $_.tbl -eq $t } | Sort-Object ord
    [void]$lines.Add("CREATE TABLE `"$t`" (")
    $defs = New-Object System.Collections.ArrayList
    foreach ($c in $tcols) {
        $typ = Map-SqlType $c.dtype $c.maxlen $c.prec $c.scale
        $nullstr = if ($c.nullable) { '' } else { ' NOT NULL' }
        $ident = if ($c.ident) { ' GENERATED BY DEFAULT AS IDENTITY' } else { '' }
        $def = "  `"$($c.col)`" $typ$ident$nullstr"
        [void]$defs.Add($def)
    }
    # primary key
    $pk = $null
    if ($idxMap.ContainsKey($t)) { $pk = $idxMap[$t] | Where-Object { $_.is_pk } | Select-Object -First 1 }
    if ($pk) {
        $colsPk = $idxCols["$t|$($pk.idx_name)"] | Where-Object { $_.is_incl -eq $false } | Sort-Object ord | ForEach-Object { "`"$($_.col)`"" }
        [void]$defs.Add("  CONSTRAINT `"pk_$t`" PRIMARY KEY (" + ($colsPk -join ', ') + ")")
    }
    [void]$lines.Add(($defs -join ",`n"))
    [void]$lines.Add(');')
}

# non-PK indexes
foreach ($t in $tables) {
    if (-not $idxMap.ContainsKey($t)) { continue }
    $n = 0
    foreach ($ix in ($idxMap[$t] | Where-Object { -not $_.is_pk })) {
        $n++
        $colsIx = $idxCols["$t|$($ix.idx_name)"] | Sort-Object ord
        $keys = @()
        foreach ($c in ($colsIx | Where-Object { $_.is_incl -eq $false })) {
            $keys += "`"$($c.col)`"" + $(if ($c.is_desc) { ' DESC' } else { '' })
        }
        if (-not $keys) { continue }
        $uniq = if ($ix.is_unique -or $ix.is_uq_con) { 'UNIQUE ' } else { '' }
        $name = if ($ix.is_uq_con) { "uq_${t}_$n" } else { "ix_${t}_$n" }
        [void]$lines.Add("CREATE $uniq INDEX `"$name`" ON `"$t`" (" + ($keys -join ', ') + ");")
    }
}
[void]$lines.Add('COMMIT;')

[System.IO.File]::WriteAllLines("$outDir\01_ddl.sql", $lines)
Write-Output ("wrote 01_ddl.sql : {0} lines, {1} tables" -f $lines.Count, $tables.Count)
